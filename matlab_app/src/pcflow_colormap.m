function cmap = pcflow_colormap(name, n)
%PCFLOW_COLORMAP 界面配色表（MATLAB / Octave 通用，不依赖工具箱）。
%   'speed'     速度：深紫—蓝—青绿—黄（感知均匀，近似 viridis）
%   'heat'      温度：黑—紫—红—橙—浅黄（感知均匀，近似 inferno）
%   'diverging' 发散：蓝—白—红（温差、涡量、压力，0 为白）
%   锚点取自 matplotlib 配色（9 点线性插值，与原表的差异肉眼不可辨）。
    if nargin < 2, n = 256; end
    switch name
        case 'speed'
            k = [0.267 0.005 0.329; 0.283 0.141 0.458; 0.254 0.265 0.530; 0.207 0.372 0.553; ...
                 0.164 0.471 0.558; 0.128 0.567 0.551; 0.135 0.659 0.518; 0.267 0.749 0.441; ...
                 0.478 0.821 0.318; 0.741 0.873 0.150; 0.993 0.906 0.144];
        case 'heat'
            k = [0.001 0.000 0.014; 0.087 0.045 0.224; 0.258 0.039 0.406; 0.416 0.090 0.433; ...
                 0.578 0.148 0.404; 0.735 0.216 0.330; 0.866 0.317 0.226; 0.955 0.463 0.106; ...
                 0.988 0.645 0.040; 0.964 0.845 0.261; 0.988 0.998 0.645];
        case 'diverging'
            k = [0.23 0.30 0.75; 0.55 0.69 0.99; 0.87 0.87 0.87; 0.96 0.60 0.48; 0.71 0.02 0.15];
        otherwise
            error('pcflow_colormap:name', '未知配色：%s', name);
    end
    x = linspace(0, 1, size(k, 1));
    xi = linspace(0, 1, n)';
    cmap = [interp1(x, k(:,1), xi), interp1(x, k(:,2), xi), interp1(x, k(:,3), xi)];
end
