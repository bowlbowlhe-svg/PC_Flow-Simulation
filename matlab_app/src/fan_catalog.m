function cat = fan_catalog()
%FAN_CATALOG 风扇型号库。
%   每个型号：size [mm]、rpm_min/rpm_max、cfm_max（满速自由风量）、noise_max（满速噪音 [dB(A)]）、
%   pmax_pa（满速最大静压）、pq_curve（P/Pmax 在 Q/Qmax = 0,0.2,…,1.0 处的值）、price [元]、label。
%   低于满速时噪音按风扇定律 L = noise_max + 50·log10(n/n_max) 计算（Fan.baseNoise），
%   Noctua 低噪适配器（L.N.A.）的标称值与此相差约 1 dB 以内。
%   满速参数取自厂家/零售商规格（v4.6.0 核对）：
%     Noctua NF-A14 PWM：1500 rpm、82.52 CFM、2.08 mmH₂O、24.6 dB(A)
%     Noctua NF-A12x25 PWM：450–2000 rpm、60.1 CFM、2.34 mmH₂O、22.6 dB(A)
%     Noctua NF-A9 PWM：400–2000 rpm、46.44 CFM、2.28 mmH₂O、22.8 dB(A)
%     Phanteks T30-120（默认"性能"档 2000 rpm）：67 CFM、27.3 dB(A)；静压按 3000 rpm 的 7.11 mmH₂O 以风扇定律折算
%     Phanteks M25 Gen2 140：350–1800 rpm、101.78 CFM、2.23 mmH₂O、36.4 dB(A)
%     Arctic P14 PWM：200–1700 rpm、72.8 CFM、2.4 mmH₂O、0.3 sone（标注约 22.5 dB(A)）
%     Arctic P12 PWM：200–1800 rpm、56.3 CFM、2.2 mmH₂O、0.3 sone（标注约 22.5 dB(A)）
%     Thermalright TL-C12C（双塔风冷原配，Tower120）：1550 rpm、66.17 CFM、1.53 mmH₂O、25.6 dB(A)
%   P-Q 曲线为读图近似；没标最低转速的取常见 PWM 下限。Stock120/GPU80/PSU120 为通用内置风扇的近似参数。
%   v4.5 及以前的型号名 RX120、RX140（数据并非真实型号）读取配置时改为 T30、M25_140（见 fan_model_alias）。
    generic = [1.00 0.92 0.79 0.60 0.36 0.00];
    mmH2O = 9.80665;                       % 1 mmH₂O = 9.80665 Pa
    cat = struct( ...
        'NF_A14', spec(140, 300, 1500, 82.52, 24.6, 2.08*mmH2O, [1.00 0.91 0.78 0.59 0.34 0.00], 249, 'Noctua NF-A14 PWM'), ...
        'NF_A12', spec(120, 450, 2000, 60.1,  22.6, 2.34*mmH2O, [1.00 0.93 0.80 0.62 0.36 0.00], 229, 'Noctua NF-A12x25 PWM'), ...
        'NF_A9',  spec(92,  400, 2000, 46.44, 22.8, 2.28*mmH2O, [1.00 0.89 0.74 0.55 0.32 0.00], 129, 'Noctua NF-A9 PWM'), ...
        'M25_140', spec(140, 350, 1800, 101.78, 36.4, 2.23*mmH2O, [1.00 0.95 0.85 0.70 0.45 0.00], 139, 'Phanteks M25 Gen2 140'), ...
        'T30',    spec(120, 400, 2000, 67,    27.3, 7.11*mmH2O*(2000/3000)^2, [1.00 0.94 0.83 0.67 0.42 0.00], 219, 'Phanteks T30-120'), ...
        'P14',    spec(140, 200, 1700, 72.8,  22.5, 2.4*mmH2O,  [1.00 0.92 0.77 0.57 0.32 0.00], 68,  'Arctic P14 PWM'), ...
        'P12',    spec(120, 200, 1800, 56.3,  22.5, 2.2*mmH2O,  [1.00 0.92 0.77 0.57 0.32 0.00], 55,  'Arctic P12 PWM'), ...
        'Stock120', spec(120, 600, 2200, 65,  32,   20.0, generic, 0, '机箱原装 120mm'), ...
        'Tower120', spec(120, 300, 1550, 66.17, 25.6, 1.53*mmH2O, generic, 0, 'CPU 塔扇（Thermalright TL-C12C）'), ...
        'GPU80',    spec(80,  800, 2600, 45,  34,   20.0, generic, 0, '显卡 80mm 风扇'), ...
        'PSU120',   spec(120, 500, 1800, 50,  30,   20.0, generic, 0, '电源 120mm 风扇'));
end

function s = spec(sz, rmin, rmax, cfm, nMax, pmax, pq, price, label)
    s = struct('size', sz, 'rpm_min', rmin, 'rpm_max', rmax, 'cfm_max', cfm, ...
               'noise_max', nMax, 'pmax_pa', pmax, 'pq_curve', pq, 'price', price, 'label', label);
end
